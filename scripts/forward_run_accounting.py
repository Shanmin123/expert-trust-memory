"""The forward run's return, broken out position by position and denominator by
denominator.

Section 5.7 reports one figure: the ten sessions returned $9.64, or 0.01% of the cash
committed. This script is the working behind it, kept with the materials rather than in
the dissertation. It answers two questions a reader of that figure will have.

Where does $9.64 come from? Eighteen holdings of about $5,000 each, whose results run
from -$386 to +$306 and largely cancel.

Is 0.01% an artefact of the denominator? No. Six readings of "the money the system put
into stock" are computed below and all of them land between 0.009% and 0.013%.

Both tables are read from the broker's own record, the same two files the checks in
scripts/verify_from_series.py read:

    reports/paper_forward/transactions_2026-08-14.csv
    reports/paper_forward/marks_2026-08-14.json

    PYTHONPATH=src python scripts/forward_run_accounting.py
    PYTHONPATH=src python scripts/forward_run_accounting.py --out reports/paper_forward/accounting.md
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FWD = ROOT / "reports" / "paper_forward"

#: AAPL, MSFT and NVDA were in the paper account before the window opened and are not
#: part of the book Section 5.7 reports. verify_from_series.py excludes the same three.
BEFORE = {"AAPL", "MSFT", "NVDA"}
START = "2026-08-03"

#: The commission schedule the dissertation charges, from Section 4.3.
PER_SHARE, MIN_COMMISSION, MAX_RATE = 0.0049, 0.99, 0.01
ACCOUNT_CASH = 100_000.0


def read_record() -> tuple[list[tuple], float]:
    """The window's fills as (date, symbol, side, quantity, net cash), and dividends."""
    legs: list[tuple] = []
    dividends = 0.0
    with (FWD / "transactions_2026-08-14.csv").open(encoding="utf-8") as fh:
        for row in csv.reader(fh):
            if len(row) < 13 or row[0] != "Transaction History" or row[1] != "Data":
                continue
            date, side, symbol, quantity, net = row[2], row[5], row[6], row[7], row[12]
            if date < START or symbol in BEFORE:
                continue
            if side in ("Buy", "Sell"):
                legs.append((date, symbol, side, float(quantity.replace(",", "")),
                             float(net.replace(",", ""))))
            elif side == "Payment in Lieu":
                dividends += float(net.replace(",", ""))
    return legs, dividends


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, help="write the tables here as markdown")
    args = ap.parse_args()

    legs, dividends = read_record()
    marks = json.loads((FWD / "marks_2026-08-14.json").read_text(encoding="utf-8"))

    buys = sum(n for _, _, side, _, n in legs if side == "Buy")
    sells = sum(n for _, _, side, _, n in legs if side == "Sell")
    quantity: dict[str, float] = {}
    cash: dict[str, float] = {}
    legcount: dict[str, int] = {}
    for _, symbol, _, q, n in legs:
        quantity[symbol] = quantity.get(symbol, 0.0) + q
        cash[symbol] = cash.get(symbol, 0.0) + n
        legcount[symbol] = legcount.get(symbol, 0) + 1

    book = {s: q for s, q in quantity.items() if abs(q) > 1e-9}
    value = sum(q * marks[s] for s, q in book.items() if marks.get(s))
    result = value + buys + sells + dividends

    lines: list[str] = []
    w = lines.append
    w("# The forward run's return, in full")
    w("")
    w("Generated by `scripts/forward_run_accounting.py` from the broker's transaction")
    w("record and the closing marks. Section 5.7 of the dissertation reports the last")
    w("line of the second table.")
    w("")
    w("## Where the result comes from")
    w("")
    w("| Stock | Shares held | Net cash | Mark, 14 Aug | Value | Result | Fills |")
    w("|---|---:|---:|---:|---:|---:|---:|")
    rows = []
    for symbol in quantity:
        held = book.get(symbol, 0.0)
        v = held * marks[symbol] if marks.get(symbol) and held else 0.0
        rows.append((v + cash[symbol], symbol, held, cash[symbol],
                     marks.get(symbol), v, legcount[symbol]))
    for pnl, symbol, held, c, mark, v, n in sorted(rows):
        mk = f"{mark:,.2f}" if mark else "closed"
        w(f"| {symbol} | {held:,.0f} | {c:,.2f} | {mk} | {v:,.2f} | {pnl:,.2f} | {n} |")
    w(f"| **total** | | **{buys + sells:,.2f}** | | **{value:,.2f}** | "
      f"**{value + buys + sells:,.2f}** | **{len(legs)}** |")
    w("")
    w(f"Payments in lieu of dividends add ${dividends:,.2f}, so the ten sessions "
      f"returned ${result:,.2f}.")
    w("")
    w("## What the run put to work")
    w("")
    committed, running = {}, 0.0
    for date in sorted({d for d, _, _, _, _ in legs}):
        running += sum(n for dd, _, _, _, n in legs if dd == date)
        committed[date] = -running
    average = sum(committed.values()) / len(committed)

    w("| | Amount |")
    w("|---|---:|")
    for label, amount in (
            ("Gross cash spent on buys", -buys),
            ("Cash that came back on sells", sells),
            ("Net cash into stock", -(buys + sells)),
            ("Most committed on any one session", max(committed.values())),
            ("Average committed over the ten sessions", average),
            ("The book's value at the close", value),
            ("The account's starting cash", ACCOUNT_CASH)):
        w(f"| {label} | {amount:,.2f} |")
    w("")
    w("Section 5.7 states the return against net cash into stock. The other amounts "
      "are the run's own record; the whole range from average committed to gross "
      "bought leaves the reported figure at 0.01% either way, so nothing here turns "
      "on the choice.")
    w("")
    w("## Capital committed at each session close, on cost")
    w("")
    w("| Session | Committed |")
    w("|---|---:|")
    for date, amount in committed.items():
        w(f"| {date} | {amount:,.2f} |")
    w("")
    w("## One thing the figure does not charge")
    w("")
    exit_commission = sum(
        min(max(MIN_COMMISSION, PER_SHARE * abs(q)), MAX_RATE * abs(q) * marks[s])
        for s, q in book.items() if marks.get(s))
    w(f"Selling the book at those marks would cost ${exit_commission:,.2f} on the "
      f"schedule of Section 4.3, which would make the result "
      f"${result - exit_commission:,.2f}. It is not charged, because "
      f"`verify_from_series.py::net` charges commission on each change in exposure and "
      f"a position still open on the last session has not changed. The backtest's own "
      f"terminal positions are marked the same way, so the two are on one convention.")
    w("")

    text = "\n".join(lines)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
